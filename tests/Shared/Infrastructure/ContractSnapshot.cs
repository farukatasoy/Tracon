using System.Text;

namespace Tracon.Tests.Common;

/// <summary>
/// A sorted list of names kept in the repository: the contract of one surface that is not .NET API
/// (SSE event names, telemetry names, configuration keys, error codes, CLI commands). Phase 238.
/// </summary>
/// <remarks>
/// <para>
/// The test that owns a surface builds the list from the code and calls <see cref="Verify"/>. The committed file
/// and the code must say the same; a difference is red. The release rehearsal
/// (<c>scripts/sozlesme_kirilma.py</c>) compares the file with the one at the baseline tag: a line that is gone is
/// a breaking change, a line that is new is not. Without this file the rehearsal has nothing to compare, because
/// ApiCompat reads .NET assemblies only.
/// </para>
/// <para>
/// Refresh after a deliberate change:
/// <c>TRACON_SOZLESME_REFRESH=1 dotnet test --project &lt;project&gt; -c Release</c>. A removed line goes through the
/// release notes first; see the 1.x rules in <c>reference/versioning.md</c>.
/// </para>
/// </remarks>
internal static class ContractSnapshot
{
    /// <summary>The environment variable that rewrites the committed files from the code.</summary>
    public const string RefreshEnvVar = "TRACON_SOZLESME_REFRESH";

    private const int MaxListed = 25;

    /// <summary>Compares <paramref name="names"/> with the committed snapshot, or rewrites it when the refresh variable is set.</summary>
    /// <param name="snapshotPath">The snapshot, as a repository-relative path with forward slashes.</param>
    /// <param name="generatedBy">The test file that owns the surface, as a repository-relative path.</param>
    /// <param name="meaning">What one line of the file names (one sentence, without a trailing period).</param>
    /// <param name="names">The names the code declares. Duplicates and blank names are a defect of the caller.</param>
    public static void Verify(string snapshotPath, string generatedBy, string meaning, IEnumerable<string> names)
    {
        var sorted = names.ToList();
        sorted.Sort(StringComparer.Ordinal);

        sorted.ShouldNotContain(static name => string.IsNullOrWhiteSpace(name), "A blank name cannot be a line of the snapshot.");
        sorted.Distinct(StringComparer.Ordinal).Count().ShouldBe(sorted.Count, "Two entries share one name; the snapshot would hide one of them.");

        var current = Render(generatedBy, meaning, sorted);
        var path = PathOf(snapshotPath);

        if (string.Equals(Environment.GetEnvironmentVariable(RefreshEnvVar), "1", StringComparison.Ordinal))
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, current);
        }

        File.Exists(path).ShouldBeTrue(
            $"'{path}' does not exist. Generate it with {RefreshEnvVar}=1 (see ContractSnapshot).");

        var committed = File.ReadAllText(path).ReplaceLineEndings("\n");

        if (!string.Equals(current, committed, StringComparison.Ordinal))
        {
            throw new ShouldAssertException(Describe(snapshotPath, current, committed));
        }
    }

    /// <summary>Reads the lines of a committed snapshot, comments left out.</summary>
    /// <param name="snapshotPath">The snapshot, as a repository-relative path with forward slashes.</param>
    /// <returns>The names, in file order.</returns>
    public static IReadOnlyList<string> Read(string snapshotPath) => Body(File.ReadAllText(PathOf(snapshotPath)).ReplaceLineEndings("\n"));

    private static string PathOf(string snapshotPath) => System.IO.Path.Combine(RepoRoot.Path, snapshotPath);

    private static string Render(string generatedBy, string meaning, IReadOnlyList<string> sorted)
    {
        var builder = new StringBuilder();
        builder.Append("# ").Append(meaning).Append(": one line per name.\n");
        builder.Append("# Generated by ").Append(generatedBy).Append(" - never edit by hand.\n");
        builder.Append("# The release rehearsal compares this file with the one at the baseline tag: a line that is gone is a\n");
        builder.Append("# breaking change for a consumer, a new line is not (scripts/sozlesme_kirilma.py).\n");

        foreach (var name in sorted)
        {
            builder.Append(name).Append('\n');
        }

        return builder.ToString();
    }

    private static List<string> Body(string text) => text
        .Split('\n', StringSplitOptions.RemoveEmptyEntries)
        .Where(static line => !line.StartsWith('#'))
        .ToList();

    private static string Describe(string snapshotPath, string current, string committed)
    {
        var now = Body(current);
        var then = Body(committed);
        var added = now.Except(then, StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList();
        var removed = then.Except(now, StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList();

        static string Listed(char sign, List<string> lines) => string.Join(
            Environment.NewLine,
            lines.Take(MaxListed).Select(line => $"{sign} {line}")) + (lines.Count > MaxListed ? $"{Environment.NewLine}  ... +{lines.Count - MaxListed} more" : "");

        return $"{snapshotPath} is stale: {added.Count} name(s) in the code but not in the file (+), " +
               $"{removed.Count} in the file but not in the code (-).{Environment.NewLine}" +
               $"{Listed('+', added)}{Environment.NewLine}{Listed('-', removed)}{Environment.NewLine}" +
               $"A name that is gone or changed is a breaking change for its consumers: name it in the release notes. " +
               $"Then refresh: {RefreshEnvVar}=1 dotnet test --project <project> -c Release";
    }
}
