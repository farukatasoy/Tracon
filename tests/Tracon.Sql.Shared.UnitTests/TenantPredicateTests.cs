using System.Reflection;
using System.Text.RegularExpressions;

namespace Tracon.SqlProviders.Tests;

/// <summary>
/// A query that reads or writes a table keyed by tenant names the tenant, or is listed here with the reason it does not.
/// </summary>
/// <remarks>
/// <para>
/// The store coverage audit counts methods: a method is covered when a contract names it, or exempt when it carries
/// <c>[TenantAgnostic]</c>. A method name on a list is a claim, and nothing checked that the query behind it filters.
/// This test reads the other end. It takes the SQL text each provider sends, finds the tables whose migrations give
/// them a <c>tenant_id</c> column, and asks each statement for a tenant predicate. A query written for one tenant's
/// rows that forgot the predicate (the session owner lookup that matched on <c>id</c> alone is the shape) fails here
/// whatever list its method sits on.
/// </para>
/// <para>
/// Two limits. The check is on text: a predicate that is present but wrong passes. And an <c>INSERT</c> is not asked
/// for a predicate, because a row is written under the tenant it names; the null-tenant check below still reads it.
/// </para>
/// </remarks>
public sealed class TenantPredicateTests
{
    /// <summary>
    /// Queries that touch a tenant table without naming the tenant, and why that is right. Each one is called with
    /// an identifier the caller already holds, or sweeps every tenant on purpose.
    /// </summary>
    private static readonly Dictionary<string, string> TenantFreeQueries = new(StringComparer.Ordinal)
    {
        // The row's own writer finishes, renews or reports it. The identifier comes from the job queue or the
        // lease the worker holds and never from a request.
        ["CompleteEvalRun"] = ById,
        ["MarkEvalRunRunning"] = ById,
        ["CompleteJob"] = ById,
        ["MarkJobRunning"] = ById,
        ["ReleaseJobForRetry"] = ById,
        ["RenewJobLease"] = ById,
        ["ReportJobItem"] = ById,
        ["LeaseJob"] = "A worker leases the next due job of any tenant; the lease then carries the job's own identifier.",
        ["CompleteRetentionRun"] = ById,
        ["UpdateRetentionRunProgress"] = ById,
        ["TryClaimJobScheduleNextRun"] = ById,
        ["TouchRunHeartbeat"] = ById,
        ["TouchApiKeyLastUsed"] = "Stamps a key that authentication has just found by its hash.",
        ["SelectWebhookDelivery"] = ById,
        ["UpdateWebhookDeliveryResult"] = ById,
        ["UpdateWebhookSubscriptionOutcome"] = ById,
        ["UpsertConversation"] = "The identifier is generated by the store and restored only from the session's own saved state.",
        ["UpsertVoiceSession"] = "The identifier is generated by the live voice host and never appears on a request.",

        // Maintenance and health work that covers the whole installation on purpose.
        ["ClaimOrphanedRuns"] = Sweep,
        ["ExpirePendingApprovals"] = Sweep,
        ["ExpireWorkflowRequests"] = Sweep,
        ["SelectDueJobSchedules"] = Sweep,
        ["SelectStrandedWorkflowRequests"] = Sweep,
        ["SelectRunningExperimentsWithCanary"] = Sweep,
        ["SelectJobQueueDepth"] = Sweep,
        ["HasApiKeyWithScope"] = "Startup asks whether any key in the installation carries a scope.",
        ["CountSessionStateGenerations"] = "The upgrade preflight reads every tenant's state; a filtered count would under-report the risk.",
        ["CountCheckpointStateGenerations"] = "The upgrade preflight reads every tenant's state; a filtered count would under-report the risk.",
        ["SampleSessionStates"] = "The upgrade preflight reads every tenant's state; a filtered sample would under-report the risk.",
        ["SampleCheckpointStates"] = "The upgrade preflight reads every tenant's state; a filtered sample would under-report the risk.",

        // The caller does not know the tenant yet: the key proves it.
        ["SelectApiKeyByHash"] = "Authentication finds the key, and with it the tenant, from the hash of what the caller presented.",
    };

    /// <summary>
    /// Queries that let a NULL tenant through, so a caller that passes none gets every tenant. Each one is either the
    /// writer of a run, which holds the run's identifier and carries no expectation to enforce, or a listing whose
    /// tenant filter is optional.
    /// </summary>
    private static readonly Dictionary<string, string> NullTenantQueries = new(StringComparer.Ordinal)
    {
        ["InsertRunEvent"] = RunWriter,
        ["InsertToolInvocation"] = RunWriter,
        ["InsertNonTokenUsage"] = RunWriter,
        ["UpdateLateToolInvocation"] = RunWriter,
        ["UpdateRunCompletion"] = RunWriter,
        ["UpdateRunCost"] = RunWriter,
        ["SelectJobs"] = "The tenant filter is optional by contract; the HTTP list always passes the caller's tenant.",
        ["SelectEvalRuns"] = "The tenant filter is optional by contract; the HTTP list always passes the caller's tenant.",
    };

    private const string ById = "Updates or reads a row by an identifier the caller already holds, from the job queue or a lease, never from a request.";

    private const string Sweep = "Maintenance work that covers every tenant in one pass.";

    private const string RunWriter =
        "The run's own writer passes its expected tenant; a null expectation means a takeover whose ambient tenant differs from the run's.";

    private static readonly Regex TableReference = new(
        @"\b(?:FROM|JOIN|UPDATE|INTO)\s+(?<table>[\w.\[\]""]+)",
        RegexOptions.CultureInvariant | RegexOptions.IgnoreCase | RegexOptions.ExplicitCapture,
        TimeSpan.FromSeconds(1));

    private static readonly Regex TenantPredicate = new(
        @"\btenant_id\b\s*(?:=|<>|!=|\bIN\b|\bIS\b)|=\s*[\w.\[\]]*\btenant_id\b|\bON\b[^;]*\btenant_id\b",
        RegexOptions.CultureInvariant | RegexOptions.IgnoreCase,
        TimeSpan.FromSeconds(1));

    private static readonly Regex NullTenantPassesThrough = new(
        @"@tenant_id\s+IS\s+NULL",
        RegexOptions.CultureInvariant | RegexOptions.IgnoreCase,
        TimeSpan.FromSeconds(1));

    [Theory]
    [InlineData("PostgreSql")]
    [InlineData("SqlServer")]
    [InlineData("Sqlite")]
    public void Every_query_on_a_tenant_table_names_the_tenant_or_is_listed_with_a_reason(string provider)
    {
        var tenantTables = TenantTables(provider);
        var unlisted = TenantFreeNames(provider, tenantTables)
            .Where(name => !TenantFreeQueries.ContainsKey(name))
            .ToList();

        tenantTables.Count.ShouldBeGreaterThan(30, "the migrations name too few tenant tables for the check to mean anything");
        unlisted.ShouldBeEmpty(
            "These queries read or write a table keyed by tenant and carry no tenant predicate: " +
            string.Join(", ", unlisted) + ". Filter by tenant, or add the query to TenantFreeQueries with the reason.");
    }

    [Fact]
    public void Every_listed_tenant_free_query_still_exists_and_still_names_no_tenant()
    {
        var stillFree = new HashSet<string>(StringComparer.Ordinal);

        foreach (var provider in Providers)
        {
            stillFree.UnionWith(TenantFreeNames(provider, TenantTables(provider)));
        }

        TenantFreeQueries.Keys.Where(name => !stillFree.Contains(name)).ShouldBeEmpty(
            "A query on the list now names a tenant or is gone. Take it off the list so the exemption does not outlive its reason.");
    }

    [Theory]
    [InlineData("PostgreSql")]
    [InlineData("SqlServer")]
    [InlineData("Sqlite")]
    public void A_query_that_lets_a_null_tenant_through_is_listed_with_a_reason(string provider)
    {
        var unlisted = Render(provider)
            .Where(query => NullTenantPassesThrough.IsMatch(query.Text))
            .Select(static query => query.Name)
            .Where(name => !NullTenantQueries.ContainsKey(name))
            .ToList();

        unlisted.ShouldBeEmpty(
            "These queries read `@tenant_id IS NULL OR ...`, so a caller that passes no tenant gets every tenant: " +
            string.Join(", ", unlisted) + ". Require the tenant, or add the query to NullTenantQueries with the reason.");
    }

    [Fact]
    public void Every_listed_null_tenant_query_still_exists_and_still_lets_a_null_through()
    {
        var stillOpen = new HashSet<string>(StringComparer.Ordinal);

        foreach (var provider in Providers)
        {
            stillOpen.UnionWith(Render(provider)
                .Where(query => NullTenantPassesThrough.IsMatch(query.Text))
                .Select(static query => query.Name));
        }

        NullTenantQueries.Keys.Where(name => !stillOpen.Contains(name)).ShouldBeEmpty(
            "A query on the list no longer lets a null tenant through, or is gone. Take it off the list.");
    }

    private static string[] Providers => ["PostgreSql", "SqlServer", "Sqlite"];

    private static HashSet<string> TenantTables(string provider)
        => MigrationSchema.Read(ProviderAssembly(provider))
            .Where(static table => table.Value.Columns.Contains("tenant_id", StringComparer.Ordinal))
            .Select(static table => table.Key)
            .ToHashSet(StringComparer.Ordinal);

    /// <summary>The queries that touch a tenant table, are not an INSERT, and carry no tenant predicate.</summary>
    private static List<string> TenantFreeNames(string provider, HashSet<string> tenantTables)
        => [.. Render(provider)
            .Where(query => !query.Text.TrimStart().StartsWith("INSERT", StringComparison.OrdinalIgnoreCase))
            .Where(query => TableReference.Matches(query.Text)
                .Any(match => tenantTables.Contains(TableName(match.Groups["table"].Value))))
            .Where(query => !TenantPredicate.IsMatch(query.Text))
            .Select(static query => query.Name)];

    /// <summary>Drops the quoting and the schema qualifier or table prefix: <c>[tracon].[jobs]</c>, <c>tracon.jobs</c> and <c>tracon_jobs</c> are <c>jobs</c>.</summary>
    private static string TableName(string reference)
    {
        var bare = reference.Replace("[", string.Empty, StringComparison.Ordinal)
            .Replace("]", string.Empty, StringComparison.Ordinal)
            .Replace("\"", string.Empty, StringComparison.Ordinal);

        var dot = bare.LastIndexOf('.');

        if (dot >= 0)
        {
            return bare[(dot + 1)..];
        }

        return bare.StartsWith("tracon_", StringComparison.Ordinal) ? bare["tracon_".Length..] : bare;
    }

    private static List<(string Name, string Text)> Render(string provider)
    {
        object queries = provider switch
        {
            "PostgreSql" => new PostgresQueries("tracon"),
            "SqlServer" => new SqlServerQueries("tracon"),
            _ => new SqliteQueries("tracon_"),
        };

        return [.. queries.GetType()
            .GetProperties(BindingFlags.Public | BindingFlags.Instance)
            .Where(static property => property.PropertyType == typeof(string) && property.GetIndexParameters().Length == 0)
            .Select(property => (property.Name, Text: (string?)property.GetValue(queries) ?? string.Empty))
            .Where(static query => query.Text.Length > 0)];
    }

    private static Assembly ProviderAssembly(string provider) => provider switch
    {
        "PostgreSql" => typeof(PostgresQueries).Assembly,
        "SqlServer" => typeof(SqlServerQueries).Assembly,
        _ => typeof(SqliteQueries).Assembly,
    };
}
