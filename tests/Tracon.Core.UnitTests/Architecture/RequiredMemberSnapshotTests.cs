using System.Text;
using Tracon.Tests.Common;

namespace Tracon.Core.UnitTests.Architecture;

/// <summary>
/// Pins the <c>required</c> members of the public API to the checked-in
/// snapshot <c>docs/sozlesme/required-uyeler.txt</c> (Phase 237, section 237.3).
/// </summary>
/// <remarks>
/// <para>
/// Why a snapshot exists at all: measured on the .NET 10 SDK, ApiCompat does
/// not report a <c>required</c> member added to an existing type, nor an
/// optional member that becomes <c>required</c>. Both break every consumer
/// that builds the type (<c>CS9035</c>), and neither shows in the
/// <c>PublicAPI.*.txt</c> files, which do not record the modifier. The
/// release rehearsal (<c>scripts/breaking_changes.py</c>) compares this file
/// with the one at the baseline tag; this test keeps the file true to the code.
/// </para>
/// <para>
/// Refresh after a deliberate change:
/// <c>TRACON_REQUIRED_MEMBERS_REFRESH=1 dotnet test --project tests/Tracon.Core.UnitTests -c Release</c>.
/// The new lines then go through the release notes; see the 1.x rules in
/// <c>reference/versioning.md</c>.
/// </para>
/// </remarks>
public sealed class RequiredMemberSnapshotTests
{
    private const string RefreshEnvVar = "TRACON_REQUIRED_MEMBERS_REFRESH";
    private const int MaxListed = 25;

    private static readonly string[] Header =
    [
        "# The public `required` members of the tracked packages: one line per member, <namespace>.<type>.<member>.",
        "# Generated by tests/Tracon.Core.UnitTests/Architecture/RequiredMemberSnapshotTests.cs - never edit by hand.",
        "# The release rehearsal compares this file with the one at the baseline tag: a line gained by a type that",
        "# the baseline already had breaks every consumer that builds it (CS9035), and ApiCompat cannot see that.",
    ];

    [Fact]
    public void The_snapshot_matches_the_required_members_in_the_code()
    {
        var current = Render(RequiredMemberScanner.Scan(TrackedSources()));

        if (string.Equals(Environment.GetEnvironmentVariable(RefreshEnvVar), "1", StringComparison.Ordinal))
        {
            Directory.CreateDirectory(Path.GetDirectoryName(SnapshotPath)!);
            File.WriteAllText(SnapshotPath, current);
        }

        File.Exists(SnapshotPath).ShouldBeTrue(
            $"'{SnapshotPath}' does not exist. Generate it with {RefreshEnvVar}=1 (see the class remarks).");

        var committed = File.ReadAllText(SnapshotPath).ReplaceLineEndings("\n");

        if (!string.Equals(current, committed, StringComparison.Ordinal))
        {
            throw new ShouldAssertException(Describe(current, committed));
        }
    }

    [Fact]
    public void The_scan_finds_the_required_members_of_the_tracked_packages()
    {
        var lines = RequiredMemberScanner.Scan(TrackedSources());

        // A scan that finds nothing passes the test above for the wrong reason. 2026-10-24: 851 `public required`
        // in the source, 536 of them on the visible surface (the rest sit in internal types).
        lines.Count.ShouldBeGreaterThan(400);
        lines.ShouldContain(static line => string.Equals(line, "Tracon.AgentDefinition.Name", StringComparison.Ordinal));
    }

    [Fact]
    public void A_member_counts_when_the_type_around_it_is_visible()
    {
        var lines = RequiredMemberScanner.Scan(
        [
            """
            namespace Demo.Models;

            public sealed class Options
            {
                public required string Name { get; init; }
                protected required string Secret;
                internal required string Hidden { get; init; }
                private protected required string Inner;
                public string NotRequired { get; init; } = "";
                public required int First, Second;
            }

            internal sealed class Internal
            {
                public required string Name { get; init; }
            }
            """,
        ]);

        lines.ShouldBe(
        [
            "Demo.Models.Options.First",
            "Demo.Models.Options.Name",
            "Demo.Models.Options.Second",
            "Demo.Models.Options.Secret",
        ]);
    }

    [Fact]
    public void Nesting_and_partial_types_are_resolved_over_all_parts()
    {
        var lines = RequiredMemberScanner.Scan(
        [
            """
            namespace Demo
            {
                public partial class Split
                {
                    public required string A { get; init; }
                }

                public class Outer
                {
                    public class Inner { public required string B { get; init; } }
                    private class Private { public required string C { get; init; } }
                    protected internal class Guarded { public required string D { get; init; } }
                }

                internal class Closed
                {
                    public class Nested { public required string E { get; init; } }
                }

                public interface IShape
                {
                    class Defaulted { public required string F { get; init; } }
                    internal class Kept { public required string G { get; init; } }
                }
            }
            """,
            """
            namespace Demo
            {
                partial class Split
                {
                    public required string H { get; init; }
                }
            }
            """,
        ]);

        // `Split` is public through its first part; `Closed.Nested` is public inside an internal type, so it is
        // not visible; a nested type in an interface is public without a modifier; `protected internal` is seen
        // from a derived type outside the assembly.
        lines.ShouldBe(
        [
            "Demo.IShape.Defaulted.F",
            "Demo.Outer.Guarded.D",
            "Demo.Outer.Inner.B",
            "Demo.Split.A",
            "Demo.Split.H",
        ]);
    }

    [Fact]
    public void Generic_arity_is_not_part_of_the_type_name_and_records_count()
    {
        var lines = RequiredMemberScanner.Scan(
        [
            """
            namespace Demo;

            public sealed record Page<T>
            {
                public required IReadOnlyList<T> Items { get; init; }
            }

            public readonly struct Pair<TKey, TValue>
            {
                public required TKey Key { get; init; }
            }
            """,
        ]);

        lines.ShouldBe(["Demo.Page.Items", "Demo.Pair.Key"]);
    }

    private static string Render(IReadOnlyList<string> lines)
    {
        var builder = new StringBuilder();

        foreach (var header in Header)
        {
            builder.Append(header).Append('\n');
        }

        foreach (var line in lines)
        {
            builder.Append(line).Append('\n');
        }

        return builder.ToString();
    }

    private static string Describe(string current, string committed)
    {
        var now = Body(current);
        var then = Body(committed);
        var added = now.Except(then, StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList();
        var removed = then.Except(now, StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList();

        static string Listed(char sign, List<string> lines) => string.Join(
            Environment.NewLine,
            lines.Take(MaxListed).Select(line => $"{sign} {line}")) + (lines.Count > MaxListed ? $"{Environment.NewLine}  ... +{lines.Count - MaxListed} more" : "");

        return $"docs/sozlesme/required-uyeler.txt is stale: {added.Count} line(s) in the code but not in the file, " +
               $"{removed.Count} in the file but not in the code.{Environment.NewLine}" +
               $"{Listed('+', added)}{Environment.NewLine}{Listed('-', removed)}{Environment.NewLine}" +
               $"A new line on an existing type is a breaking change for its consumers (CS9035): name the type in the " +
               $"release notes. Then refresh: {RefreshEnvVar}=1 dotnet test --project tests/Tracon.Core.UnitTests -c Release";
    }

    private static HashSet<string> Body(string text) => text
        .Split('\n', StringSplitOptions.RemoveEmptyEntries)
        .Where(static line => !line.StartsWith('#'))
        .ToHashSet(StringComparer.Ordinal);

    /// <summary>
    /// Every source file of a package that tracks its public API, bin/obj/node_modules left out.
    /// </summary>
    private static IEnumerable<string> TrackedSources()
    {
        var src = Path.Combine(RepoRoot.Path, "src");

        foreach (var package in Directory.EnumerateDirectories(src).Order(StringComparer.Ordinal))
        {
            if (!File.Exists(Path.Combine(package, "PublicAPI.Unshipped.txt")))
            {
                continue;
            }

            foreach (var file in SourceFiles(package))
            {
                yield return File.ReadAllText(file);
            }
        }
    }

    private static IEnumerable<string> SourceFiles(string directory)
    {
        foreach (var file in Directory.EnumerateFiles(directory, "*.cs"))
        {
            yield return file;
        }

        foreach (var child in Directory.EnumerateDirectories(directory))
        {
            var name = Path.GetFileName(child);

            if (name is "bin" or "obj" or "node_modules")
            {
                continue;
            }

            foreach (var file in SourceFiles(child))
            {
                yield return file;
            }
        }
    }

    private static string SnapshotPath { get; } = Path.Combine(RepoRoot.Path, "docs/sozlesme/required-uyeler.txt");
}
