#!/usr/bin/env python3
"""Writes and checks `src/Tracon.Cli/THIRD-PARTY-NOTICES.txt`.

The `tracon` tool package ships its whole publish output: the NuGet packages
Npgsql, Microsoft.Data.SqlClient, SQLitePCLRaw, Google.Protobuf and the rest
travel inside it as assemblies and native libraries, without the package that
carried their licence. This script builds the notice that travels with them.

The set of packages is read from the tool's own `Tracon.Cli.deps.json`, inside
the packed `.nupkg`, so it names what is shipped and not what the project file
asks for. For each package the licence text comes from, in this order:

1. a `LICENSE*` file the package itself carries;
2. `scripts/third_party_licenses/packages/<PackageId>.txt`, for a package that
   carries no licence file and whose upstream text is not a standard one;
3. the standard text of the SPDX expression the package declares
   (`scripts/third_party_licenses/spdx/<expression>.txt`), under the
   `copyright` line of the package's nuspec.

A package that cannot be resolved by any of the three stops the script: a
notice with a gap is worse than no notice. The texts that Microsoft packages
carry for the code inside them (`THIRD-PARTY-NOTICES.TXT`) are appended once
per distinct text.

The output names no version, so a dependency bump that keeps the package set
and the licence texts leaves the file unchanged.

    python3 scripts/third_party_notices.py --package <Tracon.Cli.nupkg>          # check
    python3 scripts/third_party_notices.py --package <Tracon.Cli.nupkg> --write  # rewrite
"""
from __future__ import annotations

import argparse
import dataclasses
import json
import os
import pathlib
import re
import sys
import xml.etree.ElementTree as ElementTree
import zipfile
from collections.abc import Iterable

ROOT = pathlib.Path(__file__).resolve().parent.parent
NOTICE_SOURCE = pathlib.PurePath("src", "Tracon.Cli", "THIRD-PARTY-NOTICES.txt")
DEPS_ENTRY = "tools/net10.0/any/Tracon.Cli.deps.json"
LICENSE_DIRECTORY = pathlib.PurePath("scripts", "third_party_licenses")

RULE = "=" * 80
LICENSE_FILE_PATTERN = re.compile(r"^licen[sc]e(\.[^.]+)?$", re.IGNORECASE)
BUNDLED_NOTICE_PATTERN = re.compile(r"^third[-_ ]party[-_ ]notices?(\.[^.]+)?$", re.IGNORECASE)
NOTICE_FILE_PATTERN = re.compile(r"^notice(\.[^.]+)?$", re.IGNORECASE)

HEADER = """Tracon.Cli - third-party notices

The `tracon` tool ships the NuGet packages below next to its own code, as
assemblies and native libraries. Each block is a licence text, headed by every
package it applies to. Where a package carries a licence file, the text is that
file. Where it carries none, the text is the standard text of the licence the
package declares, under the copyright line from its package metadata.

This file is generated by scripts/third_party_notices.py. Do not edit it by hand.
"""


class NoticeError(Exception):
    """A package whose licence cannot be resolved, or a package that cannot be read."""


@dataclasses.dataclass(frozen=True)
class Entry:
    package_id: str
    label: str
    text: str
    bundled: tuple[str, ...]


def global_packages_folder() -> pathlib.Path:
    configured = os.environ.get("NUGET_PACKAGES")
    return pathlib.Path(configured) if configured else pathlib.Path.home() / ".nuget" / "packages"


def packages_from_deps(deps_json: str) -> list[tuple[str, str]]:
    """(id, version) of every NuGet package the tool's dependency manifest lists."""
    libraries = json.loads(deps_json).get("libraries", {})
    packages = []
    for key, library in libraries.items():
        if library.get("type") != "package":
            continue
        package_id, _, version = key.partition("/")
        packages.append((package_id, version))
    return sorted(packages, key=lambda item: item[0].lower())


def _clean(text: str) -> str:
    lines = text.replace("\r\n", "\n").replace("\r", "\n").split("\n")
    return "\n".join(line.rstrip() for line in lines).strip("\n") + "\n"


def _read(path: pathlib.Path) -> str:
    return _clean(path.read_bytes().decode("utf-8-sig"))


def _nuspec(package_directory: pathlib.Path) -> ElementTree.Element:
    matches = sorted(package_directory.glob("*.nuspec"))
    if not matches:
        raise NoticeError(f"{package_directory} has no nuspec")
    return ElementTree.fromstring(matches[0].read_bytes().decode("utf-8-sig"))


def _metadata(nuspec: ElementTree.Element, name: str) -> str | None:
    element = nuspec.find(f".//{{*}}{name}")
    if element is None or element.text is None or not element.text.strip():
        return None
    return element.text.strip()


def _files(package_directory: pathlib.Path, pattern: re.Pattern[str]) -> list[pathlib.Path]:
    return sorted(
        (path for path in package_directory.iterdir() if path.is_file() and pattern.match(path.name)),
        key=lambda path: path.name.lower())


def _copyright_line(package_id: str, nuspec: ElementTree.Element) -> str:
    copyright_text = _metadata(nuspec, "copyright")
    if copyright_text:
        return copyright_text
    authors = _metadata(nuspec, "authors")
    if authors:
        return f"Copyright (c) {authors}"
    raise NoticeError(f"{package_id}: the package names no copyright and no authors")


def resolve_entry(package_id: str, version: str, packages_folder: pathlib.Path, licenses: pathlib.Path) -> Entry:
    package_directory = packages_folder / package_id.lower() / version
    if not package_directory.is_dir():
        raise NoticeError(
            f"{package_id} {version} is not in {packages_folder}; restore the tool project first")
    nuspec = _nuspec(package_directory)
    license_element = nuspec.find(".//{*}license")
    kind = license_element.get("type") if license_element is not None else None
    value = (license_element.text or "").strip() if license_element is not None else ""

    own_files = _files(package_directory, LICENSE_FILE_PATTERN)
    if kind == "file" and value:
        declared = package_directory / pathlib.PurePosixPath(value)
        if declared.is_file():
            own_files = [declared]

    notice_files = _files(package_directory, NOTICE_FILE_PATTERN)
    override = licenses / "packages" / f"{package_id}.txt"

    if own_files:
        text = "\n".join(_read(path) for path in own_files)
        label = value if kind == "expression" and value else own_files[0].name
    elif override.is_file():
        text = _read(override)
        label = value or "see text"
    elif kind == "expression" and value:
        body_path = licenses / "spdx" / f"{value}.txt"
        if not body_path.is_file():
            raise NoticeError(
                f"{package_id} declares the licence '{value}' and carries no licence file: "
                f"add its standard text as {LICENSE_DIRECTORY / 'spdx' / (value + '.txt')} "
                f"or, for a text that is not the standard one, as "
                f"{LICENSE_DIRECTORY / 'packages' / (package_id + '.txt')}")
        text = _copyright_line(package_id, nuspec) + "\n\n" + _read(body_path)
        label = value
    else:
        raise NoticeError(
            f"{package_id} carries no licence file and declares no licence expression: "
            f"add {LICENSE_DIRECTORY / 'packages' / (package_id + '.txt')}")

    for path in notice_files:
        text += "\n" + _read(path)

    bundled = tuple(_read(path) for path in _files(package_directory, BUNDLED_NOTICE_PATTERN))
    return Entry(package_id, label, text, bundled)


def render(packages: Iterable[tuple[str, str]], packages_folder: pathlib.Path, licenses: pathlib.Path) -> str:
    entries = [resolve_entry(package_id, version, packages_folder, licenses) for package_id, version in packages]
    parts = [HEADER]
    # Packages whose licence text is the same share one block. Every package still
    # has its own `<id> (<licence>)` line, which is what a reader and the package
    # test look for.
    groups: dict[tuple[str, str], list[Entry]] = {}
    for entry in entries:
        groups.setdefault((entry.label, entry.text), []).append(entry)
    for (label, text), members in sorted(groups.items(), key=lambda item: item[1][0].package_id.lower()):
        headings = "\n".join(f"{member.package_id} ({label})" for member in members)
        parts.append(f"\n{RULE}\n{headings}\n{RULE}\n\n{text}")

    bundled_by_text: dict[str, list[str]] = {}
    for entry in entries:
        for text in entry.bundled:
            bundled_by_text.setdefault(text, []).append(entry.package_id)
    if bundled_by_text:
        parts.append(
            f"\n{RULE}\nNotices that the packages above carry for the code inside them\n{RULE}\n"
            "\nEach text below is printed once, under the packages that carry it.\n")
        for text, owners in sorted(bundled_by_text.items(), key=lambda item: (item[1][0].lower(), item[0])):
            parts.append(f"\n{RULE}\n{', '.join(owners)}\n{RULE}\n\n{text}")
    return "".join(parts)


def deps_from_package(nupkg: pathlib.Path) -> str:
    with zipfile.ZipFile(nupkg) as archive:
        try:
            return archive.read(DEPS_ENTRY).decode("utf-8-sig")
        except KeyError:
            raise NoticeError(f"{nupkg.name} has no {DEPS_ENTRY}") from None


def expected_notice(nupkg: pathlib.Path, root: pathlib.Path = ROOT) -> str:
    return render(
        packages_from_deps(deps_from_package(nupkg)),
        global_packages_folder(),
        root / LICENSE_DIRECTORY)


def drift_error(root: pathlib.Path, nupkg: pathlib.Path) -> str | None:
    """None when the checked-in notice is what the packed tool needs; otherwise one sentence."""
    source = root / NOTICE_SOURCE
    if not source.is_file():
        return f"{NOTICE_SOURCE} is missing; write it with scripts/third_party_notices.py --write"
    try:
        expected = expected_notice(nupkg, root)
    except NoticeError as error:
        return str(error)
    if source.read_bytes().decode("utf-8") != expected:
        return (f"{NOTICE_SOURCE} does not match the packages the tool ships; "
                f"run `python3 scripts/third_party_notices.py --package {nupkg.name} --write` and commit it")
    return None


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--package", required=True, type=pathlib.Path, help="the packed Tracon.Cli .nupkg")
    parser.add_argument("--write", action="store_true", help="rewrite the notice instead of checking it")
    options = parser.parse_args(argv)

    if options.write:
        try:
            text = expected_notice(options.package)
        except NoticeError as error:
            print(f"error: {error}", file=sys.stderr)
            return 1
        (ROOT / NOTICE_SOURCE).write_bytes(text.encode("utf-8"))
        print(f"wrote {NOTICE_SOURCE}")
        return 0

    error = drift_error(ROOT, options.package)
    if error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    print(f"{NOTICE_SOURCE} matches {options.package.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
