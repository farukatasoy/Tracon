using Microsoft.Agents.AI;
using Microsoft.Extensions.AI;

namespace Tracon;

/// <summary>
/// Run options that let the caller determine a run's identifier, its place
/// in the tree, and its budget.
/// </summary>
/// <remarks>
/// <para>
/// The wrapper writing the run record normally generates its own identifier
/// and does not report it outward. A streaming endpoint, however, must know
/// the identifier <strong>before the first frame</strong>: only then can the
/// client associate the streamed response with the run record. Having the
/// caller generate the identifier solves this without an extra notification
/// channel or ambient state, and follows the same approach as
/// <see cref="RunStartInfo.RunId"/>.
/// </para>
/// <para>
/// The <see cref="ParentRunId"/>, <see cref="RootRunId"/>, <see cref="Depth"/>,
/// and <see cref="Budget"/> fields are filled in by <c>ChildAgentInvoker</c>
/// when an agent calls another agent. They do not need to be filled in by
/// hand; if they are, the run is placed at the specified spot in the tree.
/// </para>
/// <para>
/// This type <em>carries no</em> public <c>ChatOptions</c>. Tracon's own
/// endpoints resolve the model options from the agent definition, so a run that
/// starts at an endpoint cannot change them. Code that runs an agent directly can
/// pass Microsoft Agent Framework's <c>ChatClientAgentRunOptions</c> instead; that
/// run then has no identifier, tree position, or budget that the caller sets. The
/// run-recording wrapper refuses such options when they set what the definition
/// owns (the model, sampling, the response format, a chat client factory, or a
/// tool that runs); it accepts added instructions and tool declarations.
/// </para>
/// <para>
/// Only the outermost run-recording wrapper reads this type. It hands the
/// agents inside it a plain <see cref="AgentRunOptions"/> that carries the base
/// properties (a <c>ChatClientAgentRunOptions</c> when a workflow step was given
/// model options for the run), and the run's identity reaches them through
/// <c>TraconRunContext</c>. Microsoft Agent Framework's function-invocation
/// middleware rejects any other options type, so an <c>IAgentDecorator</c>
/// that adds it must have an <c>Order</c> above 0.
/// </para>
/// </remarks>
public sealed class TraconRunOptions : AgentRunOptions
{
    /// <summary>Creates a new options object.</summary>
    public TraconRunOptions()
    {
    }

    private TraconRunOptions(TraconRunOptions other)
        : base(other)
    {
        RunId = other.RunId;
        ParentRunId = other.ParentRunId;
        RootRunId = other.RootRunId;
        Depth = other.Depth;
        Budget = other.Budget;
        Kind = other.Kind;
        AgentVersion = other.AgentVersion;
        ExperimentId = other.ExperimentId;
        Variant = other.Variant;
        SessionId = other.SessionId;
        ReplayOfRunId = other.ReplayOfRunId;
        ContinuedFromRunId = other.ContinuedFromRunId;
        BeforePendingApprovalIsPublished = other.BeforePendingApprovalIsPublished;
        ParameterValues = other.ParameterValues;
        ChatOptions = other.ChatOptions;
        SuspendsWorkflowOnApproval = other.SuspendsWorkflowOnApproval;
        SessionHasNoRecord = other.SessionHasNoRecord;
        AcceptsToolInput = other.AcceptsToolInput;
        ToolInputAnswers = other.ToolInputAnswers;
        BeforePendingToolInputIsPublished = other.BeforePendingToolInputIsPublished;
    }

    /// <summary>
    /// The run identifier to use. If <see langword="null"/>, the identifier
    /// is generated by the wrapper that writes the run record.
    /// </summary>
    /// <remarks>
    /// The value must be time-ordered; <c>TraconId.NewId()</c> ensures
    /// this. A random identifier produced by <c>Guid.NewGuid()</c> fragments
    /// the storage index.
    /// </remarks>
    public Guid? RunId { get; init; }

    /// <summary>
    /// The identifier of the run that started this run. <see langword="null"/>
    /// for the root run.
    /// </summary>
    public Guid? ParentRunId { get; init; }

    /// <summary>
    /// The identifier of the run at the root of the tree. <see langword="null"/> if the
    /// run itself is the root.
    /// </summary>
    /// <remarks>
    /// The value is denormalized: fetching a whole tree through <see
    /// cref="ParentRunId"/> would require a recursive query; a single indexed query on
    /// the root identifier is enough.
    /// </remarks>
    public Guid? RootRunId { get; init; }

    /// <summary>The depth in the tree. The root run is 0.</summary>
    public int Depth { get; init; }

    /// <summary>
    /// The budget <strong>shared</strong> across the tree. If
    /// <see langword="null"/>, the wrapper opening the root run produces a
    /// budget from its settings.
    /// </summary>
    /// <remarks>
    /// The object is the <em>same instance</em> at every run in the tree. If
    /// it were copied, each branch would get its own budget and the limit
    /// would lose its meaning.
    /// </remarks>
    public AgentRunBudget? Budget { get; init; }

    /// <summary>
    /// This run's kind. If <see langword="null"/>, the wrapper assumes
    /// <see cref="RunKind.Agent"/>.
    /// </summary>
    /// <remarks>
    /// The eval job processor gives <see cref="RunKind.Eval"/> for
    /// every case run; this lets <see cref="IRunStore.GetStatisticsAsync"/>
    /// exclude these synthetic calls from the summary.
    /// </remarks>
    public RunKind? Kind { get; init; }

    /// <summary>
    /// The definition version this run measures. If <see langword="null"/>,
    /// the wrapper uses the (current) version from the agent's catalog
    /// summary. For runs resolved by an A/B experiment, this field is
    /// filled in because the compiled agent's <em>actual</em> version may
    /// differ from the current one.
    /// </summary>
    public int? AgentVersion { get; init; }

    /// <summary>The identifier of the experiment this run belongs to. <see langword="null"/> for a non-experiment run.</summary>
    public Guid? ExperimentId { get; init; }

    /// <summary>
    /// The name of the experiment variant this run is assigned to. <see
    /// langword="null"/> for a non-experiment run.
    /// </summary>
    public string? Variant { get; init; }

    /// <summary>
    /// The identifier of the session at the root of the tree. Filled in for child runs;
    /// the root run reads its identifier from its own <c>AgentSession</c>.
    /// </summary>
    /// <remarks>
    /// <para>
    /// This field only feeds <c>AgentRunScope.SessionId</c>; it <strong>does not
    /// change</strong> a run record's <c>session_id</c> column. The two concepts are
    /// separate: the column says "the run was started with this session," while the
    /// scope says "content produced here belongs to this session." On a child agent
    /// call, MAF passes no session, but the produced attachment still belongs to the
    /// root session.
    /// </para>
    /// <para>
    /// This matters for retention: an attachment written without a session counts as
    /// orphaned, and the retention policy deletes it.
    /// </para>
    /// </remarks>
    public string? SessionId { get; init; }

    /// <summary>
    /// If this run is a replay, the source run's identifier. The
    /// value is written to the <c>runs.replay_of_run_id</c> column.
    /// </summary>
    /// <remarks>
    /// This field is meaningful only for the <strong>root</strong> run; a
    /// replay's child calls do not carry their own lineage.
    /// </remarks>
    public Guid? ReplayOfRunId { get; init; }

    /// <summary>
    /// If this run continues an interrupted run, the interrupted run's
    /// identifier. The value is written to the <c>runs.continued_from_run_id</c> column.
    /// </summary>
    /// <remarks>
    /// This field is meaningful only for the <strong>root</strong> run; a
    /// continuation's child calls do not carry their own lineage.
    /// </remarks>
    public Guid? ContinuedFromRunId { get; init; }

    /// <summary>
    /// Gets the work that must be DONE AND VISIBLE before the run is closed with
    /// <see cref="RunStatus.AwaitingApproval"/>.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <see cref="RunStatus.AwaitingApproval"/> is TERMINAL and is the signal a
    /// consumer polls on. Whoever records the pending approval does so AFTER the
    /// agent call returns — but the run is closed INSIDE that call, so without this
    /// hook the status is published first and <c>GET /api/approvals/pending</c>
    /// answers an empty list for a run that already says it is waiting. The window
    /// was not a race: the order was fixed, so it was open on EVERY such run.
    /// </para>
    /// <para>
    /// The callback receives the messages the run produced and runs on BOTH the
    /// buffered and the streaming path, immediately before the terminal status is
    /// written. It runs only when the run actually ends by requesting approval;
    /// anything it throws fails the run, which is correct — a published
    /// <see cref="RunStatus.AwaitingApproval"/> whose approval was never recorded
    /// is unanswerable.
    /// </para>
    /// <para>
    /// The second parameter carries the <see cref="ToolApprovalPresentation"/> already
    /// resolved for each pending request, keyed by <c>ToolApprovalRequestContent.RequestId</c>
    /// — the same resolution the closing run event's payload was built from. A caller that
    /// also persists a <see cref="PendingApproval"/> row (as <c>AgentRunJobHandler</c> does)
    /// reads the presentation from here instead of resolving it a second time.
    /// </para>
    /// </remarks>
    public Func<IEnumerable<ChatMessage>, IReadOnlyDictionary<string, ToolApprovalPresentation?>, CancellationToken, ValueTask>? BeforePendingApprovalIsPublished { get; init; }

    /// <summary>
    /// The parameter values the run's agent was compiled with. <see langword="null"/>
    /// when the caller bound no values (and so recorded none).
    /// </summary>
    /// <remarks>
    /// <para>
    /// Internal on purpose: the value is not an instruction to the recording
    /// wrapper, it is the record of an instruction already followed. The caller
    /// that compiled the agent (the <c>/run</c> endpoint, a job handler, a
    /// workflow step) passes the SAME dictionary it bound, and the wrapper writes
    /// it to <see cref="RunInputRecord.Parameters"/> so a replay and a resume run
    /// with the source run's values.
    /// </para>
    /// <para>
    /// Setting it on options for an agent that was NOT compiled with those values
    /// would record a claim the run never followed; there is no validation here.
    /// </para>
    /// </remarks>
    internal IReadOnlyDictionary<string, string>? ParameterValues { get; init; }

    /// <summary>
    /// Gets the model options a sub-run was given for this run only, passed on to the agent as
    /// <c>ChatClientAgentRunOptions</c>.
    /// </summary>
    /// <remarks>
    /// A workflow step is Tracon's sub-agent wrapper, and the wrapper builds these options itself.
    /// Microsoft Agent Framework's handoff step gives its agent the handoff tools and instructions on
    /// <c>ChatClientAgentRunOptions</c>; without this member the wrapper dropped them, and no workflow
    /// handed off. The wrapper checks them with the same rule as a caller's own run options.
    /// </remarks>
    internal ChatOptions? ChatOptions { get; init; }

    /// <summary>
    /// Gets whether a tool approval the run asks for suspends the WORKFLOW that called it
    /// instead of failing the run.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Set only by a workflow step's sub-agent wrapper. A sub-run that ends by asking for approval
    /// is <see cref="RunStatus.Failed"/>, because an agent tree cannot wait in its middle. A workflow can:
    /// Microsoft Agent Framework turns the request into an external request, the workflow stops at its checkpoint,
    /// and the answer continues it on a new run. The step's row then closes <see cref="RunStatus.AwaitingApproval"/>,
    /// the way a root run's does.
    /// </para>
    /// <para>
    /// It is not inherited: the wrapper of a sub-agent the step's agent calls builds its own options
    /// without it, so a sub-agent's approval is still refused below the step.
    /// </para>
    /// </remarks>
    internal bool SuspendsWorkflowOnApproval { get; init; }

    /// <summary>
    /// Gets whether <see cref="SessionId"/> names a session that has no <c>sessions</c> record, so no
    /// session delete, retention policy or session-keyed erasure can find what is stored under it.
    /// </summary>
    /// <remarks>
    /// A workflow run's session id is its own and never gets a session record. Every run below the workflow
    /// (an agent step, the sub-agents it calls) inherits the id and so inherits this flag. Conversation
    /// memory writes nothing for such a run: a record it kept could not be deleted with its session.
    /// </remarks>
    internal bool SessionHasNoRecord { get; init; }

    /// <summary>
    /// Gets whether the caller of this run can answer a tool's request for user input
    /// (MCP elicitation) on the next turn of the session.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Set only by the management API's run endpoint, whose response carries the request and
    /// whose next request carries the answer. Every other surface leaves it off, and an MCP
    /// server's request on such a run gets an explicit <c>decline</c>: an OpenAI-compatible
    /// call, an A2A task, an MCP tool call and a queued run have no channel for the answer.
    /// </para>
    /// <para>
    /// Never inherited: a sub-agent cannot suspend its parent's tree (the rule that governs approvals), so the wrapper of
    /// a sub-agent builds its own options without it.
    /// </para>
    /// </remarks>
    internal bool AcceptsToolInput { get; init; }

    /// <summary>
    /// Gets the user's answers to earlier tool input requests, in the order the server asked
    /// them, keyed by the call identity of the call that replays the suspended tool call.
    /// </summary>
    /// <remarks>
    /// The call that was suspended runs again from its start: the tool wrapper
    /// answers the server's requests with these, in order, instead of asking the user again.
    /// A request beyond the last answer suspends the run again.
    /// </remarks>
    internal IReadOnlyDictionary<string, IReadOnlyList<ToolInputAnswer>>? ToolInputAnswers { get; init; }

    /// <summary>
    /// Gets the callback that runs immediately before a run closes
    /// <see cref="RunStatus.AwaitingInput"/> because a tool asked for user input.
    /// </summary>
    /// <remarks>
    /// The same moment and the same guarantee as <see cref="BeforePendingApprovalIsPublished"/>:
    /// the request is announced to the caller before the terminal status is visible, and a
    /// failure fails the run, because a published status whose request nobody saw cannot be answered.
    /// </remarks>
    internal Func<IReadOnlyList<PendingToolInput>, CancellationToken, ValueTask>? BeforePendingToolInputIsPublished { get; init; }

    /// <inheritdoc />
    /// <remarks>
    /// Cloning preserves all fields. Otherwise, a middleware layer copying
    /// the options would silently drop the identifier, and the wrapper would
    /// generate its own — the identifier reported to the client would then
    /// correspond to no record at all. The same trap is more insidious for
    /// the tree fields: a dropped <see cref="Depth"/> value silently disables
    /// recursion protection.
    /// </remarks>
    public override AgentRunOptions Clone() => new TraconRunOptions(this);
}
